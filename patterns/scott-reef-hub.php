<h2 class="wp-block-heading sr-eyebrow" id="whats-at-stake">What’s at stake?</h2>
<!-- /wp:heading -->

<!-- wp:columns {"className":"sr-intro-cols"} -->
<div class="wp-block-columns sr-intro-cols"><!-- wp:column {"width":"46%"} -->
<div class="wp-block-column" style="flex-basis:46%"><!-- wp:heading {"level":3,"className":"sr-h3"} -->
<h3 class="wp-block-heading sr-h3">Scott Reef is an extraordinary place. One worth protecting.</h3>
<!-- /wp:heading --></div>
<!-- /wp:column -->

<!-- wp:column {"width":"46%"} -->
<div class="wp-block-column" style="flex-basis:46%"><!-- wp:paragraph -->
<p>Scott Reef is Australia’s largest freestanding oceanic reef system, a 15-million-year-old marine wonderland and vital habitat for endangered pygmy blue whales, nesting green turtles and other threatened wildlife.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>But Woodside wants to drill up to 57 toxic wells around Scott Reef as part of its Browse gas project. If it goes ahead, this remote ocean sanctuary could face decades of seismic blasting, industrial activity and climate pollution, as well as the risk of a catastrophic oil spill.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Scott Reef is simply too important to risk for more dirty gas.</p>
<!-- /wp:paragraph -->

